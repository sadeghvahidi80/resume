  function applyForm(scope, T, p) {
    setText(document.querySelector(scope + " .t-caption"), T[p + "_kicker"]);
    setText(document.querySelector(scope + " .t-h1"), T[p + "_title"]);
    var desc = document.querySelector(scope + " p.t-body");
    if (desc) setText(desc, T[p + "_desc"]);
    var notice = document.querySelector(scope + " .form-notice");
    if (notice) setText(notice, T[p + "_notice"], "html");
    var privH = document.querySelector(scope + " .privacy-notice h3");
    if (privH) setText(privH, T[p + "_priv_h"]);
    var privP = document.querySelector(scope + " .privacy-notice p");
    if (privP) setText(privP, T[p + "_priv_p"]);
    setAll(scope + " .form-section-title", T[p + "_sec"]);
    setAll(scope + " .form-group > label", T[p + "_labels"]);
    setAll(scope + " [placeholder]", T[p + "_ph"], "ph");
    if (p === "thf") {
      setAll(scope + " .radio-group .radio-option", T.thf_mode);
      setAll(scope + " .tag-group", null);
      var tags = document.querySelectorAll(scope + " .tag-btn");
      T.thf_age.concat(T.thf_area).forEach(function (v, i) { if (tags[i]) tags[i].textContent = v; });
      setAll(scope + " .checkbox-item span", T.thf_checks);
    }
    if (p === "appf") {
      var sels = document.querySelectorAll(scope + " select");
      if (sels[0]) setAllSel(sels[0], T.appf_age);
      if (sels[1]) setAllSel(sels[1], T.appf_ch);
      var urg = document.querySelectorAll(scope + " .radio-option");
      urg.forEach(function (box, i) {
        var divs = box.querySelectorAll("div");
        if (divs[0] && T.appf_urg_t[i]) divs[0].textContent = T.appf_urg_t[i];
        if (divs[1] && T.appf_urg_d[i]) divs[1].textContent = T.appf_urg_d[i];
      });
      var small = document.querySelector(scope + " .form-group p");
      if (small) setText(small, T.appf_small);
    }
    if (p === "donf") {
      var sel = document.querySelector(scope + " select");
      if (sel) setAllSel(sel, T.donf_ch);
      setAll(scope + " .radio-group .radio-option", T.donf_type);
      var chk = document.querySelector(scope + " .checkbox-item span");
      if (chk) setText(chk, T.donf_check);
    }
    if (p === "hamf") {
      setAll(scope + " .radio-group .radio-option", T.hamf_type);
    }
    var btn = document.querySelector(scope + ' button[data-form]');
    if (btn && !btn.disabled) setText(btn, T[p + "_submit"]);
    var okKey = { thf: "therapist", appf: "applicant", donf: "donate", hamf: "hamyar" }[p];
    var ok = document.getElementById("success-" + okKey);
    if (ok && ok.style.display === "block") setText(ok, T[p + "_success"], "html");
    else if (ok) ok.setAttribute("data-i18n-success", p + "_success");
  }

